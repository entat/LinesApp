package com.lines.app;

public class SignData {
    String LineNumber;
    String Station;
    String Row1;
    String Row2;
    String Row3;
    String Row4;
    String Row5;


    public SignData(String lineNumber, String station, String row1, String row2, String row3, String row4, String row5) {
        LineNumber = lineNumber;
        Station = station;
        Row1 = row1;
        Row2 = row2;
        Row3 = row3;
        Row4 = row4;
        Row5 = row5;
    }



}
